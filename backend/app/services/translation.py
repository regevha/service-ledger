"""Translation service: Hebrew service reports to English, before classification
and extraction (docs: claude/proposal-hebrew-translation.md).

`translate()` is the one function the worker's translate job calls. It answers
one of three ways:

- `None`: the document is not Hebrew; nothing to translate or review.
- a `TranslationResult`: an English text for a person to review, plus the pages
  that were left out because they are instrument QC printouts.
- raises `TranslationError`: the translation could not be made (no API key for
  a Hebrew text, an API failure, a malformed answer).

Rules that come from the proposal and the live scan of the two samples:

- The page itself goes to the model (the PDF or the image), never the text
  layer: a Hebrew text layer is stored in visual (reversed) order, so
  extracted lines that mix Hebrew with numbers come out scrambled. The text
  layer is used only to measure how Hebrew a document is.
- Identifiers (serials, order, part and work-order numbers, model names) and
  dates are kept exactly as printed.
- Instrument QC printouts (the Daily QC pages that follow a service form) are
  ignored: not translated, not classified, not extracted. They stay in the
  original file. A person can ask for a page to be included.
- With no API key a Hebrew text is refused with a clear message, never passed
  on silently. Stub mode (USE_LIVE_CLAUDE off) translates only a file whose
  name says "hebrew", with a fixed fixture, so end-to-end tests can run.
"""
from __future__ import annotations

import logging
import re
from typing import NamedTuple

from app.config import get_settings
from app.models import Attachment
from app.services.claude_client import call_claude_tool, extract_tool_use, get_client as _get_client
from app.services.documents import UnsupportedDocumentError, claude_content_block
from app.services.errors import TranslationError
from app.services.text_reader import extract_text

logger = logging.getLogger("app.services.translation")
settings = get_settings()

_TOOL_NAME = "record_translation"

# Hebrew letters (the Hebrew block without the presentation forms).
_HEBREW = re.compile(r"[א-ת]")
_LETTER = re.compile(r"[^\W\d_]", re.UNICODE)

# What counts as an identifier: a token with a digit, at least 4 characters,
# letters digits and the separators - / . _ only (serials, order and part
# numbers, work orders, report numbers).
_IDENTIFIER = re.compile(r"[A-Za-z0-9][A-Za-z0-9\-_/.]{2,}[A-Za-z0-9]")

STUB_HEBREW_MARKER = "hebrew"

STUB_TRANSLATION = """Service report No. 2046 (stub translation)

Date: 13.08.2026
Customer: Example University
Instrument: Example Analyzer, S.N Y1033
Service description: System upgrade, annual preventive maintenance
Parts replaced: 1 x Upgrade kit (P/N N7-97566)
Work: 20   Travel: 6
Notes: Performed with a representative of the manufacturer.
Engineer signature: signed. Customer signature: blank."""

_PROMPT = """This is a scanned or generated service report, probably in Hebrew with some \
English terms. Translate it to English so that a person can read both side by side, \
and record the result with the tool.

Rules:
- Translate faithfully, in the order of the page, keeping the structure of forms and \
tables as readable text (one table row per line, cells separated by " | ").
- Keep identifiers EXACTLY as printed and never translate or transliterate them: serial \
numbers, work-order, report, customer and order numbers, part numbers, model and product \
names and codes, dates and units. List every identifier you kept in `identifiers`.
- Keep dates as printed (13.08.2026, 22/09/26); do not reformat them. Keep numbers that \
carry no unit as printed; do not invent a unit.
- Mark anything you cannot read as [unreadable] in the text and describe it in `notes`. \
Never guess a character of an identifier.
- IGNORE instrument QC printouts: pages generated by the instrument or its software that \
report a quality-control or calibration check (for example a "Daily QC Report" or "QC Setup \
Status" page, tables of channel or detector names with gain, median and %rCV columns, bead \
lot IDs), usually attached after the service form. Do not translate them. List each such \
page in `ignored_pages` with its 1-based page number and a short reason. A small QC result \
inside the service form itself is not a QC printout: translate it.
- `hebrew_share` is your estimate (0 to 1) of the share of the letters on the translated \
pages that are Hebrew. `source_language` is the main language of the document ("he", "en", \
"mixed" or another code)."""


class TranslationResult(NamedTuple):
    source_language: str
    hebrew_share: float
    translated_text: str
    ignored_pages: list[dict]
    identifiers: list[str]
    notes: list[str]
    reader: str = "model"


def hebrew_share(text: str) -> float:
    """Share of the letters in `text` that are Hebrew, 0.0 when there are none."""
    letters = _LETTER.findall(text)
    if not letters:
        return 0.0
    return len(_HEBREW.findall(text)) / len(letters)


def text_layer_hebrew_share(attachment: Attachment) -> float | None:
    """Hebrew share measured on the file's own text layer; None for an image or
    a PDF with no text (nothing to measure), or an unreadable file."""
    try:
        with open(attachment.file_path, "rb") as f:
            text = extract_text(f.read())
    except OSError:
        return None
    if not text.strip():
        return None
    return hebrew_share(text)


def is_hebrew_text_layer(attachment: Attachment) -> bool:
    share = text_layer_hebrew_share(attachment)
    return share is not None and share > settings.hebrew_letter_threshold


def identifiers_in(text: str) -> list[str]:
    """Identifier-looking tokens (with a digit) in `text`, first occurrence order."""
    seen: dict[str, None] = {}
    for token in _IDENTIFIER.findall(text):
        if any(c.isdigit() for c in token):
            seen[token] = None
    return list(seen)


def identifier_check(listed: list[str], translated_text: str, original_text: str = "") -> dict:
    """Which identifiers do not appear verbatim in the translation. `listed` are
    the identifiers the model says it kept; `original_text` (the text layer, when
    there is one) adds the identifiers found there too."""
    candidates: dict[str, None] = {}
    for item in listed:
        if isinstance(item, str) and item.strip():
            candidates[item.strip()] = None
    for item in identifiers_in(original_text):
        candidates[item] = None
    missing = [c for c in candidates if c not in translated_text]
    return {"checked": len(candidates), "missing": missing}


def _stub_translate(attachment: Attachment, include_pages: list[int]) -> TranslationResult | None:
    name = attachment.file_path.replace("\\", "/").rsplit("/", 1)[-1].lower()
    if STUB_HEBREW_MARKER not in name:
        return None
    ignored = [
        {"page": p, "reason": "Instrument QC printout"} for p in (2, 3) if p not in include_pages
    ]
    text = STUB_TRANSLATION
    for p in sorted(set(include_pages)):
        text += f"\n\n[Page {p} included at the reviewer's request: stub text]"
    return TranslationResult("he", 0.8, text, ignored, ["2046", "Y1033", "N7-97566"], [], reader="stub")


def _live_translate(attachment: Attachment, include_pages: list[int]) -> TranslationResult:
    try:
        document_block = claude_content_block(attachment.file_path)
    except UnsupportedDocumentError as e:
        raise TranslationError(str(e)) from e

    prompt = _PROMPT
    if include_pages:
        pages = ", ".join(str(p) for p in sorted(set(include_pages)))
        prompt += (
            f"\n\nThe reviewer asked for page(s) {pages} to be translated even if they look like "
            "QC printouts: translate them and do not list them in `ignored_pages`."
        )

    tool = {
        "name": _TOOL_NAME,
        "description": "Record the English translation of this service report and the pages that were ignored.",
        "input_schema": {
            "type": "object",
            "properties": {
                "source_language": {"type": "string"},
                "hebrew_share": {"type": "number", "minimum": 0, "maximum": 1},
                "translated_text": {"type": "string"},
                "ignored_pages": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "properties": {"page": {"type": "integer", "minimum": 1}, "reason": {"type": "string"}},
                        "required": ["page", "reason"],
                    },
                },
                "identifiers": {"type": "array", "items": {"type": "string"}},
                "notes": {"type": "array", "items": {"type": "string"}},
            },
            "required": ["source_language", "hebrew_share", "translated_text", "ignored_pages", "identifiers", "notes"],
        },
    }
    response = call_claude_tool(
        client=_get_client(),
        request_kwargs=dict(
            model=settings.anthropic_model,
            max_tokens=settings.translate_max_tokens,
            timeout=settings.translate_timeout_seconds,
            tools=[tool],
            tool_choice={"type": "tool", "name": _TOOL_NAME},
            messages=[{"role": "user", "content": [document_block, {"type": "text", "text": prompt}]}],
        ),
        error_cls=TranslationError,
        logger=logger,
        attachment_path=attachment.file_path,
        verb="translate",
        gerund="translating",
        noun="translation",
    )
    if getattr(response, "stop_reason", None) == "max_tokens":
        raise TranslationError(
            "The translation was cut off because the document is too long to translate in one pass. "
            "Nothing was saved."
        )
    tool_use = extract_tool_use(
        response,
        error_cls=TranslationError,
        logger=logger,
        attachment_path=attachment.file_path,
        gerund="translating",
        noun="translation",
    )
    data = tool_use.input
    try:
        share = float(data["hebrew_share"])
        text = data["translated_text"]
        language = str(data["source_language"]).strip() or "unknown"
    except (KeyError, TypeError, ValueError) as e:
        logger.error("Claude's translation response for %s was malformed: %s", attachment.file_path, e)
        raise TranslationError(f"Claude's translation response was missing or malformed fields: {e}") from e
    if not isinstance(text, str):
        raise TranslationError("Claude's translation response had no text.")

    ignored: list[dict] = []
    for item in data.get("ignored_pages") or []:
        try:
            page = int(item["page"])
        except (KeyError, TypeError, ValueError):
            continue
        if page >= 1 and page not in include_pages:
            ignored.append({"page": page, "reason": str(item.get("reason", "")).strip() or "Instrument QC printout"})
    identifiers = [i for i in (data.get("identifiers") or []) if isinstance(i, str)]
    notes = [n for n in (data.get("notes") or []) if isinstance(n, str)]
    return TranslationResult(language, min(max(share, 0.0), 1.0), text, ignored, identifiers, notes)


def translate(attachment: Attachment, include_pages: list[int] | None = None) -> TranslationResult | None:
    """Translate one attachment. See the module docstring for the three outcomes."""
    include = sorted({int(p) for p in (include_pages or [])})
    layer_share = text_layer_hebrew_share(attachment)
    if not settings.use_live_claude:
        if layer_share is not None and layer_share > settings.hebrew_letter_threshold:
            raise TranslationError(
                "This document is in Hebrew and cannot be translated without a Claude API key. "
                "Set ANTHROPIC_API_KEY and USE_LIVE_CLAUDE, then try again."
            )
        return _stub_translate(attachment, include)
    if layer_share is not None and layer_share <= settings.hebrew_letter_threshold and not include:
        return None  # a readable text layer that is not Hebrew: no model call
    result = _live_translate(attachment, include)
    if result.hebrew_share <= settings.hebrew_letter_threshold and not include:
        return None
    return result


def current_translation(attachment: Attachment):
    """The attachment's newest translation that is not superseded, or None."""
    from app.models import TranslationStatus

    # getattr: callers (and older tests) may pass a bare stand-in attachment.
    live = [t for t in getattr(attachment, "translations", []) if t.status != TranslationStatus.superseded]
    return live[-1] if live else None


def accepted_text(attachment: Attachment) -> str | None:
    """The English text a person accepted for this attachment, or None. When
    there is one, classification and extraction read this instead of the
    original document."""
    from app.models import TranslationStatus

    current = current_translation(attachment)
    if current is not None and current.status == TranslationStatus.accepted:
        return current.accepted_text or current.model_text
    return None


def source_block(attachment: Attachment) -> dict:
    """The content block classification and extraction send to the model: the
    accepted English translation as text when there is one, else the original
    document. Raises UnsupportedDocumentError for an unreadable original."""
    text = accepted_text(attachment)
    if text is not None:
        return {
            "type": "text",
            "text": (
                "The following is the reviewed English translation of the scanned service report "
                "(the original was in Hebrew). Identifiers and dates are kept as printed. Read it as the "
                "document.\n\n<document>\n" + text + "\n</document>"
            ),
        }
    return claude_content_block(attachment.file_path)


def translation_gate(attachment: Attachment) -> str | None:
    """Why classify/extract may not run on this attachment yet, or None when
    they may. A translation waiting for review or still being made blocks; so
    does a Hebrew text layer that was never translated. A discarded translation
    (use the original as today) and a `not_needed` one do not block."""
    from app.models import ExtractionJobKind, ExtractionJobStatus, TranslationStatus

    for job in attachment.extraction_jobs:
        if job.kind == ExtractionJobKind.translate and job.status in (
            ExtractionJobStatus.pending,
            ExtractionJobStatus.translating,
        ):
            return "This document is being translated — wait for the translation, then review it."
    current = current_translation(attachment)
    if current is not None:
        if current.status == TranslationStatus.pending_review:
            return "The English translation of this document is waiting for review — accept (or discard) it first."
        return None
    if is_hebrew_text_layer(attachment):
        return "This document is in Hebrew — translate it and review the translation before classifying or extracting."
    return None
